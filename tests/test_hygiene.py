from __future__ import annotations

import ast
import re
import subprocess
import sys
import unittest
from pathlib import Path

from engine.lib import redact

ROOT = Path(__file__).resolve().parent.parent
CODE_DIRS = ("engine", "board", "cli", "bin")
ENTRY_SCRIPTS = ("bin/shopfloor", "engine/bin/sf")
REPO_PACKAGES = {"engine", "board", "cli"}
ATTRIBUTION = re.compile(
    r"co-authored-by|generated with|generated by|noreply@anthropic\.com|ai assistant",
    re.IGNORECASE,
)


def _code_files():
    files = set()
    for d in CODE_DIRS:
        base = ROOT / d
        if base.is_dir():
            files.update(p for p in base.glob("**/*.py") if "__pycache__" not in p.parts)
    files.update(ROOT / s for s in ENTRY_SCRIPTS if (ROOT / s).is_file())
    return sorted(files)


def _tracked_files():
    out = subprocess.run(
        ["git", "ls-files", "-z"], cwd=ROOT, capture_output=True, check=True
    ).stdout
    names = [n for n in out.decode().split("\0") if n]
    return [ROOT / n for n in names if (ROOT / n).is_file()]


def _text(path):
    data = path.read_bytes()
    if b"\0" in data:
        return None
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError:
        return None


class Hygiene(unittest.TestCase):
    @unittest.skipUnless(
        hasattr(sys, "stdlib_module_names"), "needs sys.stdlib_module_names (3.10+)"
    )
    def test_no_third_party_imports(self):
        allowed = set(sys.stdlib_module_names) | REPO_PACKAGES
        bad = []
        for path in _code_files():
            tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
            for node in ast.walk(tree):
                if isinstance(node, ast.Import):
                    names = [a.name for a in node.names]
                elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
                    names = [node.module]
                else:
                    continue
                bad += [
                    f"{path.relative_to(ROOT)}: {n}"
                    for n in names
                    if n.split(".")[0] not in allowed
                ]
        self.assertEqual(bad, [])

    def test_no_secret_looking_strings(self):
        bad = []
        for path in _tracked_files():
            rel = path.relative_to(ROOT).as_posix()
            if rel == "board/static/mermaid.min.js":
                continue
            text = _text(path)
            if text is not None and redact.find_sensitive(text) == redact.TOKEN_KIND:
                bad.append(rel)
        self.assertEqual(bad, [])

    def test_every_module_has_future_annotations(self):
        missing = []
        for path in _code_files():
            src = path.read_text(encoding="utf-8")
            if not src.strip():
                continue
            tree = ast.parse(src, filename=str(path))
            found = any(
                isinstance(n, ast.ImportFrom)
                and n.module == "__future__"
                and any(a.name == "annotations" for a in n.names)
                for n in tree.body
            )
            if not found:
                missing.append(str(path.relative_to(ROOT)))
        self.assertEqual(missing, [])

    def test_no_ai_attribution(self):
        hits = []
        for path in _tracked_files():
            rel = path.relative_to(ROOT).as_posix()
            if rel == "LICENSE" or rel.startswith(("tests/", "scripts/", "board/static/")):
                continue
            text = _text(path)
            if text is None:
                continue
            for n, line in enumerate(text.splitlines(), 1):
                if ATTRIBUTION.search(line):
                    hits.append(f"{rel}:{n}")
        self.assertEqual(hits, [])


if __name__ == "__main__":
    unittest.main()
